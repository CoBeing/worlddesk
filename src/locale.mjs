export const strings=Object.freeze({zh,en})
export function detectLanguage(systemLanguage){
  const input=String(systemLanguage||'').toLowerCase()
  return input.startsWith('zh')?'zh':'en'
}
export function pickLanguage(systemLanguage,override){
  return ['zh','en'].includes(override)?override:detectLanguage(systemLanguage)
}
